import { z } from 'zod';
import type { PaymentMethod, SaleStatus } from '../constants';
import { PAYMENT_METHODS, SALE_STATUSES } from '../constants';
import {
  optionalTextSchema,
  paginationQuerySchema,
  positiveMoneySchema,
  searchTermSchema,
} from './common';
import { dateOnlySchema } from './inventory';

/** A percentage with at most 2 decimal places, e.g. "10" or "12.5". */
const percentSchema = z
  .string()
  .trim()
  .regex(/^\d{1,3}(\.\d{1,2})?$/, 'Must be a percentage like "10" or "12.5"')
  .refine((v) => Number(v) > 0 && Number(v) <= 100, 'Must be more than 0 and at most 100');

export const DISCOUNT_TYPES = ['AMOUNT', 'PERCENT'] as const;
export type DiscountType = (typeof DISCOUNT_TYPES)[number];

/**
 * A discount as a fixed PKR amount or a percentage. On a line it applies to
 * quantity × price; on the bill it applies to the total after line discounts.
 * Cashiers are limited to a configured share of the bill (checked by the API).
 */
export const discountSchema = z.discriminatedUnion('type', [
  z.strictObject({ type: z.literal('AMOUNT'), value: positiveMoneySchema }),
  z.strictObject({ type: z.literal('PERCENT'), value: percentSchema }),
]);
export type DiscountInput = z.infer<typeof discountSchema>;

const MAX_SALE_QUANTITY = 10_000;

/**
 * One medicine in the cart. The API picks the batches (earliest expiry first)
 * and the price (the medicine's current selling price); the client never does.
 */
const saleItemInputSchema = z.strictObject({
  medicineId: z.uuid(),
  quantity: z.number().int().min(1, 'Quantity must be at least 1').max(MAX_SALE_QUANTITY),
  discount: discountSchema.optional(),
});
export type SaleItemInput = z.infer<typeof saleItemInputSchema>;

/**
 * One tender. For CASH, `amount` is what the customer handed over; the API
 * works out the change. Card and wallet amounts are charged exactly, so they
 * may not exceed what is still owed.
 */
const paymentInputSchema = z.strictObject({
  method: z.enum(PAYMENT_METHODS),
  amount: positiveMoneySchema,
  /** Card approval code or wallet transaction id. */
  reference: optionalTextSchema(100),
});
export type PaymentInput = z.infer<typeof paymentInputSchema>;

export const createSaleBodySchema = z
  .strictObject({
    /**
     * Generated by the client once per sale (crypto.randomUUID()) and sent
     * unchanged on every retry, so a sale is never saved twice.
     */
    idempotencyKey: z.uuid(),
    items: z.array(saleItemInputSchema).min(1, 'Add at least one item').max(100),
    /** Bill-level discount, applied after line discounts. */
    discount: discountSchema.optional(),
    /** Several entries make a split payment. Empty only for a fully discounted bill. */
    payments: z.array(paymentInputSchema).max(10),
    notes: optionalTextSchema(500),
  })
  .superRefine((body, ctx) => {
    const seen = new Set<string>();
    body.items.forEach((item, i) => {
      if (seen.has(item.medicineId)) {
        ctx.addIssue({
          code: 'custom',
          path: ['items', i, 'medicineId'],
          message: 'This medicine appears twice; combine the lines',
        });
      }
      seen.add(item.medicineId);
    });
    if (body.payments.filter((p) => p.method === 'CASH').length > 1) {
      ctx.addIssue({
        code: 'custom',
        path: ['payments'],
        message: 'Enter cash as a single payment',
      });
    }
  });
export type CreateSaleBody = z.infer<typeof createSaleBodySchema>;

export const voidSaleBodySchema = z.strictObject({
  reason: z.string().trim().min(3, 'Give a reason for voiding the sale').max(500),
});
export type VoidSaleBody = z.infer<typeof voidSaleBodySchema>;

export const listSalesQuerySchema = paginationQuerySchema
  .extend({
    /** Receipt number, or part of it (case-insensitive). */
    q: searchTermSchema.optional(),
    status: z.enum(SALE_STATUSES).optional(),
    /** Ignored for cashiers, who only ever see their own sales. */
    cashierId: z.uuid().optional(),
    /** Sale dates, inclusive, as days in the pharmacy's timezone. */
    from: dateOnlySchema.optional(),
    to: dateOnlySchema.optional(),
  })
  .refine((q) => !q.from || !q.to || q.from <= q.to, {
    message: '"from" must not be after "to"',
    path: ['from'],
  });
export type ListSalesQuery = z.infer<typeof listSalesQuerySchema>;

// ─── Responses ──────────────────────────────────────────────────────────────
// All money is a PKR decimal string with 2 decimal places, e.g. "120.50".

export type SaleUserRef = { id: string; username: string; fullName: string };

/** One line per batch: FEFO may split one medicine across several lines. */
export type SaleItemDto = {
  id: string;
  medicine: { id: string; name: string; genericName: string | null; unit: string };
  batch: { id: string; batchNumber: string; expiryDate: string };
  quantity: number;
  unitPrice: string;
  /** This line's share of line and bill discounts. */
  discount: string;
  tax: string;
  /** quantity × unitPrice − discount + tax */
  lineTotal: string;
};

export type PaymentDto = {
  id: string;
  method: PaymentMethod;
  /** Amount applied to the sale. */
  amount: string;
  /** Cash handed over, when it differs from amount. */
  tendered: string | null;
  reference: string | null;
};

export type SaleSummaryDto = {
  id: string;
  receiptNumber: string;
  status: SaleStatus;
  soldAt: string;
  cashier: SaleUserRef;
  subtotal: string;
  discountTotal: string;
  taxTotal: string;
  grandTotal: string;
  changeDue: string;
  /** Total units sold across all lines. */
  itemCount: number;
  paymentMethods: PaymentMethod[];
};

export type SaleDto = Omit<SaleSummaryDto, 'itemCount' | 'paymentMethods'> & {
  idempotencyKey: string | null;
  notes: string | null;
  items: SaleItemDto[];
  payments: PaymentDto[];
  /** Cash and other tenders received in total (grandTotal + changeDue). */
  amountTendered: string;
  voidedAt: string | null;
  voidedBy: SaleUserRef | null;
  voidReason: string | null;
};
